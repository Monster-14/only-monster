CREATE DATABASE IF NOT EXISTS monster_portfolio
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_unicode_ci;

USE monster_portfolio;

CREATE TABLE IF NOT EXISTS admin_user (
  id              BIGINT PRIMARY KEY AUTO_INCREMENT,
  username        VARCHAR(32) NOT NULL UNIQUE,
  password_hash   VARCHAR(100) NOT NULL,
  last_login_at   DATETIME NULL,
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS profile (
  id           BIGINT PRIMARY KEY AUTO_INCREMENT,
  name         VARCHAR(64) NOT NULL DEFAULT 'Monster',
  headline     VARCHAR(128) NOT NULL DEFAULT '',
  bio          TEXT,
  avatar_url   VARCHAR(512) NOT NULL DEFAULT '',
  email        VARCHAR(128) NOT NULL DEFAULT '',
  github_url   VARCHAR(256) NOT NULL DEFAULT '',
  blog_url     VARCHAR(256) NOT NULL DEFAULT '',
  wechat       VARCHAR(64) NOT NULL DEFAULT '',
  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
