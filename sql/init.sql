CREATE DATABASE IF NOT EXISTS monster_portfolio
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_unicode_ci;

USE monster_portfolio;

CREATE TABLE IF NOT EXISTS admin_user (
  id              BIGINT PRIMARY KEY AUTO_INCREMENT,
  username        VARCHAR(32) NOT NULL UNIQUE,
  password_hash   VARCHAR(100) NOT NULL,
  last_login_at   DATETIME NULL,
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS profile (
  id           BIGINT PRIMARY KEY AUTO_INCREMENT,
  name         VARCHAR(64) NOT NULL DEFAULT 'Monster',
  headline     VARCHAR(128) NOT NULL DEFAULT '',
  bio          TEXT,
  avatar_url   VARCHAR(512) NOT NULL DEFAULT '',
  email        VARCHAR(128) NOT NULL DEFAULT '',
  github_url   VARCHAR(256) NOT NULL DEFAULT '',
  blog_url     VARCHAR(256) NOT NULL DEFAULT '',
  wechat       VARCHAR(64) NOT NULL DEFAULT '',
  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS project (
  id           BIGINT PRIMARY KEY AUTO_INCREMENT,
  slug         VARCHAR(80) NOT NULL UNIQUE,
  title        VARCHAR(128) NOT NULL,
  cover_url    VARCHAR(512) NOT NULL DEFAULT '',
  summary      VARCHAR(255) NOT NULL DEFAULT '',
  content      MEDIUMTEXT,
  tech_stack   VARCHAR(512) NOT NULL DEFAULT '',
  demo_url     VARCHAR(256) NOT NULL DEFAULT '',
  repo_url     VARCHAR(256) NOT NULL DEFAULT '',
  status       TINYINT NOT NULL DEFAULT 0,
  sort         INT NOT NULL DEFAULT 0,
  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS article (
  id             BIGINT PRIMARY KEY AUTO_INCREMENT,
  slug           VARCHAR(80) NOT NULL UNIQUE,
  title          VARCHAR(128) NOT NULL,
  cover_url      VARCHAR(512) NOT NULL DEFAULT '',
  summary        VARCHAR(255) NOT NULL DEFAULT '',
  content_md     MEDIUMTEXT,
  status         TINYINT NOT NULL DEFAULT 0,
  published_at   DATETIME NULL,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS message (
  id           BIGINT PRIMARY KEY AUTO_INCREMENT,
  nickname     VARCHAR(32) NOT NULL,
  email        VARCHAR(128) NOT NULL DEFAULT '',
  content      VARCHAR(500) NOT NULL,
  status       TINYINT NOT NULL DEFAULT 0,
  ip           VARCHAR(64) NOT NULL DEFAULT '',
  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
